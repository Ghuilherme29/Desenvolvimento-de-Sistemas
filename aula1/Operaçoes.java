public class Operaçoes {
   public static void main(String[] args) {
       int nota1 = 8;
       int nota2 = 5;

       int sub = nota1 - nota2;
       int media = (nota1+nota2) / 2;
       int multi = nota1 * nota2;
       int div = nota1+nota2 / 2;
       int soma = nota1 + nota2;

       System.out.println("a sua media é: " + media);
       System.out.println("A subtração da sua nota é: " + sub );
       System.out.println("A multiplicação da sua nota é: " + multi );
       System.out.println("A divisão da sua nota é: " + div );
       System.out.println("A soma da sua nota é: " + soma );
   } 
}
